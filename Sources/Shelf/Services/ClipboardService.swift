import AppKit

struct ClipItem: Codable, Identifiable, Hashable {
    enum Kind: String, Codable { case text, url, image, files }

    var id = UUID()
    var kind: Kind
    var text: String?
    var imageFile: String?      // file name inside the images folder
    var filePaths: [String]?
    var date = Date.now
    var pinned = false
    var sourceBundleID: String?

    var preview: String {
        switch kind {
        case .text, .url: text ?? ""
        case .image: "Image"
        case .files: (filePaths ?? []).map { ($0 as NSString).lastPathComponent }.joined(separator: ", ")
        }
    }
}

/// Clipboard history. macOS has no change notification for the pasteboard, so
/// we poll `changeCount` (cheap) and only read contents when it changes.
@Observable
final class ClipboardService {
    static let shared = ClipboardService()

    private(set) var items: [ClipItem] = [] {
        didSet { save() }
    }
    var isPaused = false

    @ObservationIgnored private var lastChangeCount = NSPasteboard.general.changeCount
    @ObservationIgnored private var started = false

    private static let maxItems = 200
    private static let dir = URL.applicationSupportDirectory.appending(path: "Shelf/Clipboard", directoryHint: .isDirectory)
    private static let fileURL = dir.appending(path: "history.json")
    private static let imagesDir = dir.appending(path: "images", directoryHint: .isDirectory)

    /// Types that password managers and others use to say "don't record this".
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
    ]

    private init() {
        try? FileManager.default.createDirectory(at: Self.imagesDir, withIntermediateDirectories: true)
        if let data = try? Data(contentsOf: Self.fileURL),
           let saved = try? JSONDecoder().decode([ClipItem].self, from: data) {
            items = saved
        }
    }

    func start() {
        guard !started else { return }
        started = true
        Task {
            while !Task.isCancelled {
                poll()
                try? await Task.sleep(for: .milliseconds(600))
            }
        }
    }

    private func save() {
        try? JSONEncoder().encode(items).write(to: Self.fileURL, options: .atomic)
    }

    private func poll() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount
        guard !isPaused, DockStore.shared.hasWidget(.clipboard) else { return }

        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.ignoredTypes) else { return }
        let source = NSWorkspace.shared.frontmostApplication?.bundleIdentifier

        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            add(ClipItem(kind: .files, filePaths: urls.map { $0.path(percentEncoded: false) }, sourceBundleID: source))
        } else if let string = pasteboard.string(forType: .string), !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let isURL = URL(string: string).flatMap(\.scheme).map { ["http", "https"].contains($0) } ?? false
            add(ClipItem(kind: isURL ? .url : .text, text: string, sourceBundleID: source))
        } else if let image = NSImage(pasteboard: pasteboard),
                  let tiff = image.tiffRepresentation,
                  let png = NSBitmapImageRep(data: tiff)?.representation(using: .png, properties: [:]),
                  png.count < 8_000_000 {
            let name = UUID().uuidString + ".png"
            try? png.write(to: Self.imagesDir.appending(path: name))
            add(ClipItem(kind: .image, imageFile: name, sourceBundleID: source))
        }
    }

    private func add(_ item: ClipItem) {
        // Re-copying something already in history moves it to the top.
        if let existing = items.firstIndex(where: { $0.kind == item.kind && $0.text == item.text && $0.filePaths == item.filePaths && item.kind != .image }) {
            var moved = items.remove(at: existing)
            moved.date = .now
            items.insert(moved, at: 0)
            return
        }
        items.insert(item, at: 0)
        trim()
    }

    private func trim() {
        var unpinned = items.filter { !$0.pinned }
        guard unpinned.count > Self.maxItems else { return }
        let dropped = unpinned[Self.maxItems...]
        unpinned.removeLast(unpinned.count - Self.maxItems)
        dropped.forEach(deleteImage)
        let keep = Set(dropped.map(\.id))
        items.removeAll { keep.contains($0.id) }
    }

    // MARK: Actions

    func image(for item: ClipItem) -> NSImage? {
        item.imageFile.flatMap { NSImage(contentsOf: Self.imagesDir.appending(path: $0)) }
    }

    /// Puts an item back on the clipboard (and moves it to the top).
    func copy(_ item: ClipItem) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        switch item.kind {
        case .text, .url:
            pasteboard.setString(item.text ?? "", forType: .string)
        case .image:
            if let image = image(for: item) { pasteboard.writeObjects([image]) }
        case .files:
            pasteboard.writeObjects((item.filePaths ?? []).map { URL(filePath: $0) as NSURL })
        }
        lastChangeCount = pasteboard.changeCount
        if let i = items.firstIndex(of: item) {
            var moved = items.remove(at: i)
            moved.date = .now
            items.insert(moved, at: 0)
        }
    }

    func togglePin(_ item: ClipItem) {
        guard let i = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[i].pinned.toggle()
    }

    func delete(_ item: ClipItem) {
        deleteImage(item)
        items.removeAll { $0.id == item.id }
    }

    func clearUnpinned() {
        items.filter { !$0.pinned }.forEach(deleteImage)
        items.removeAll { !$0.pinned }
    }

    private func deleteImage(_ item: ClipItem) {
        if let file = item.imageFile { try? FileManager.default.removeItem(at: Self.imagesDir.appending(path: file)) }
    }
}
